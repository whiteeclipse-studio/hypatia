import { requireCondition } from "../errors.ts";
import type { ProcessingLimits } from "../types.ts";

const blockSize = 512;
const terminatorBlocks = 2;
const endSize = blockSize * terminatorBlocks;
const sizeOffset = 124;
const sizeLength = 12;
const typeOffset = 156;
const octalRadix = 8;
const regularFile = 48;
const extendedHeader = 120;

/**
 * Rejects truncated TARs that a permissive streaming extractor might otherwise accept.
 * Counts physical headers, including PAX headers, before extraction.
 *
 * @param tar - Expanded TAR bytes.
 * @param limits - Resolved processing ceilings.
 * @throws {DocumentationError} For malformed framing, unsupported entry types, or oversized headers.
 */
export function validateTarFraming(tar: Uint8Array, limits: ProcessingLimits): void {
    requireCondition(tar.length >= endSize && tar.length % blockSize === 0, "Truncated TAR framing");
    let offset = 0;
    let headers = 0;
    while (offset < tar.length) {
        const header = tar.subarray(offset, offset + blockSize);
        if (header.every(isZero)) {
            requireCondition(
                tar.length - offset >= endSize && tar.subarray(offset).every(isZero),
                "Invalid TAR terminator",
            );
            return;
        }
        headers += 1;
        requireCondition(headers <= limits.maxFiles * terminatorBlocks, "TAR header count exceeded", "limits");
        const size = headerSize(header);
        requireCondition(size <= limits.maxFileBytes, "TAR entry exceeds file limit", "limits");
        const type = header[typeOffset];
        requireCondition(
            type === 0 || type === regularFile || type === extendedHeader,
            "Only regular TAR files and PAX paths are supported",
        );
        offset += blockSize + Math.ceil(size / blockSize) * blockSize;
        requireCondition(offset <= tar.length - endSize, "Truncated TAR entry");
    }
    requireCondition(false, "Missing TAR terminator");
}

/**
 * Reads the octal size field generated by the builder's TAR writer.
 *
 * @param header - A complete TAR header.
 * @returns Its bounded nonnegative integer size.
 * @throws {DocumentationError} For unsupported or malformed numeric encodings.
 */
function headerSize(header: Uint8Array): number {
    const field = new TextDecoder()
        .decode(header.subarray(sizeOffset, sizeOffset + sizeLength))
        .replaceAll("\0", "")
        .trim();
    requireCondition(/^[0-7]+$/u.test(field), "Invalid TAR size field");
    const size = Number.parseInt(field, octalRadix);
    requireCondition(Number.isSafeInteger(size) && size >= 0, "Invalid TAR entry size");
    return size;
}

/**
 * Checks TAR padding bytes.
 *
 * @param value - One byte.
 * @returns Whether the byte is zero.
 */
function isZero(value: number): boolean {
    return value === 0;
}
